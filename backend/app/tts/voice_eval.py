"""Listening-test harness for MOS collection (Pallika, Section 11.3 #5).

The deliverable is "ratings from 10 listeners on 5 audio samples per subject
(naturalness, clarity, pacing)". This module does the three things that need
code, and leaves the listening to humans:

    build   — synthesise 5 samples per subject into outputs/audio/voice_eval/
              and write a blind rating sheet (samples are given opaque IDs so a
              rater cannot see which voice or subject they are scoring)
    collect — read back the filled-in CSV of ratings
    report  — compute Mean Opinion Score, standard deviation and 95% CI per
              subject and per criterion, and emit a markdown table

Usage from the repo root:
    python backend/app/tts/voice_eval.py build
    # ... 10 listeners fill in outputs/audio/voice_eval/ratings.csv ...
    python backend/app/tts/voice_eval.py report
"""

import asyncio
import csv
import json
import math
import random
import statistics
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[2]
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.tts.tts_config import VOICE_MAP  # noqa: E402
from app.tts.tts_generator import TTSGenerator  # noqa: E402

EVAL_DIR = BACKEND_DIR / "outputs" / "audio" / "voice_eval"
RATINGS_CSV = EVAL_DIR / "ratings.csv"
MANIFEST_JSON = EVAL_DIR / "manifest.json"

CRITERIA = ["naturalness", "clarity", "pacing"]
SCALE_MIN, SCALE_MAX = 1, 5

# Five samples per subject, chosen to cover the notation the preprocessor must
# handle: plain prose, a formula, a unit-heavy line, a term-dense line, a NEET alert.
EVAL_SCRIPTS = {
    "physics": [
        "Newton's third law tells us that forces always occur in pairs, acting on two different bodies.",
        "The equation v² = u² + 2as connects final velocity, initial velocity, acceleration and displacement.",
        "A body of mass 4 kg accelerating at 5 m/s2 experiences a force of 20 N.",
        "In simple harmonic motion, the restoring force is proportional to the displacement from the mean position.",
        "NEET alert: watch the sign convention in mirror problems, because a single sign flips the answer.",
    ],
    "biology": [
        "The plasma membrane is a selectively permeable barrier made of a lipid bilayer with embedded proteins.",
        "During DNA replication, the leading strand is synthesised continuously in the 5' to 3' direction.",
        "Bacteria have 70S ribosomes, whereas eukaryotic cytoplasmic ribosomes are 80S.",
        "In the light reaction, NADP is reduced to NADPH while ATP is generated by photophosphorylation.",
        "NEET alert: remember that the exception is often the question, so learn every special case.",
    ],
    "chemistry": [
        "Hybridisation explains molecular geometry by mixing atomic orbitals of comparable energy.",
        "Methane burns in oxygen: CH4 + 2O2 gives CO2 and 2H2O.",
        "A tertiary halide reacts by the SN1 mechanism through a carbocation intermediate.",
        "Concentrated H2SO4 dehydrates C2H5OH at 443 K to give ethene.",
        "NEET alert: group trends have exceptions, and those exceptions are exam favourites.",
    ],
}


# ---------------------------------------------------------------------------
# build
# ---------------------------------------------------------------------------


async def build(seed: int = 92) -> None:
    """Synthesise the evaluation set and write a blind rating sheet."""
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    generator = TTSGenerator()

    manifest = []
    for subject, scripts in EVAL_SCRIPTS.items():
        for index, script in enumerate(scripts, start=1):
            sample_id = f"{subject[:3].upper()}{index:02d}"
            path = EVAL_DIR / f"{sample_id}.mp3"
            result = await generator.generate_scene_audio(script, subject, str(path))
            manifest.append({
                "sample_id": sample_id,
                "subject": subject,
                "voice": result["voice"],
                "script": script,
                "spoken_text": result["processed_text"],
                "file": path.name,
                "audio_metrics": result.get("audio_metrics", {}),
            })
            print(f"  built {sample_id}  {subject:<9} {path.name}")

    MANIFEST_JSON.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    # Blind presentation order: raters should not hear all Physics samples together.
    order = [row["sample_id"] for row in manifest]
    random.Random(seed).shuffle(order)

    with open(RATINGS_CSV, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["listener_id", "sample_id", *CRITERIA, "comments"])
        for listener in range(1, 11):
            for sample_id in order:
                writer.writerow([f"L{listener:02d}", sample_id, "", "", "", ""])

    print(f"\n{len(manifest)} samples in {EVAL_DIR}")
    print(f"Blank rating sheet: {RATINGS_CSV}")
    print(f"Presentation order is shuffled (seed={seed}) so ratings stay blind.")
    print(f"Scale: {SCALE_MIN}-{SCALE_MAX} for {', '.join(CRITERIA)}.")


# ---------------------------------------------------------------------------
# collect + report
# ---------------------------------------------------------------------------


def collect() -> list:
    """Read the filled-in ratings CSV, skipping blank and out-of-range rows."""
    if not RATINGS_CSV.exists():
        raise FileNotFoundError(f"{RATINGS_CSV} not found — run 'build' first.")

    rows = []
    with open(RATINGS_CSV, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            scores = {}
            for criterion in CRITERIA:
                raw = (row.get(criterion) or "").strip()
                if not raw:
                    continue
                try:
                    value = float(raw)
                except ValueError:
                    continue
                if SCALE_MIN <= value <= SCALE_MAX:
                    scores[criterion] = value
            if scores:
                rows.append({
                    "listener_id": row.get("listener_id", ""),
                    "sample_id": row.get("sample_id", ""),
                    "scores": scores,
                })
    return rows


def _summarise(values: list) -> dict:
    n = len(values)
    mean = statistics.fmean(values)
    sd = statistics.stdev(values) if n > 1 else 0.0
    # 95% CI using the normal approximation; adequate at n >= 30 ratings.
    margin = 1.96 * sd / math.sqrt(n) if n > 1 else 0.0
    return {
        "n": n,
        "mean": round(mean, 2),
        "std_dev": round(sd, 2),
        "ci95_low": round(mean - margin, 2),
        "ci95_high": round(mean + margin, 2),
    }


def report() -> dict:
    """Compute MOS per subject and criterion, and write a markdown table."""
    rows = collect()
    if not rows:
        print("No completed ratings found yet. Ask listeners to fill in "
              f"{RATINGS_CSV}, then re-run 'report'.")
        return {}

    manifest = json.loads(MANIFEST_JSON.read_text(encoding="utf-8")) if MANIFEST_JSON.exists() else []
    subject_of = {row["sample_id"]: row["subject"] for row in manifest}

    by_subject = {}
    overall = {criterion: [] for criterion in CRITERIA}
    for row in rows:
        subject = subject_of.get(row["sample_id"], "unknown")
        bucket = by_subject.setdefault(subject, {c: [] for c in CRITERIA})
        for criterion, value in row["scores"].items():
            bucket[criterion].append(value)
            overall[criterion].append(value)

    summary = {
        "listeners": len({r["listener_id"] for r in rows}),
        "rated_samples": len({r["sample_id"] for r in rows}),
        "by_subject": {
            subject: {c: _summarise(v) for c, v in buckets.items() if v}
            for subject, buckets in by_subject.items()
        },
        "overall": {c: _summarise(v) for c, v in overall.items() if v},
    }

    lines = [
        "# Mean Opinion Score (MOS) — TTS Listening Test",
        "",
        f"Listeners: {summary['listeners']} · Samples rated: {summary['rated_samples']} "
        f"· Scale: {SCALE_MIN}-{SCALE_MAX}",
        "",
        "| Subject | " + " | ".join(c.title() + " (mean ± SD)" for c in CRITERIA) + " |",
        "| --- | " + " | ".join(["---"] * len(CRITERIA)) + " |",
    ]
    for subject in sorted(summary["by_subject"]):
        cells = []
        for criterion in CRITERIA:
            stat = summary["by_subject"][subject].get(criterion)
            cells.append(f"{stat['mean']} ± {stat['std_dev']}" if stat else "—")
        lines.append(f"| {subject} | " + " | ".join(cells) + " |")

    overall_cells = []
    for criterion in CRITERIA:
        stat = summary["overall"].get(criterion)
        overall_cells.append(f"**{stat['mean']} ± {stat['std_dev']}**" if stat else "—")
    lines.append("| **All** | " + " | ".join(overall_cells) + " |")

    out_path = BACKEND_DIR / "outputs" / "benchmarks" / "tts_mos_scores.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("\n".join(lines))
    print(f"\nMarkdown written to {out_path}")
    return summary


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

    command = sys.argv[1] if len(sys.argv) > 1 else "build"
    if command == "build":
        print(f"Building listening test for {len(VOICE_MAP)} subjects...")
        asyncio.run(build())
    elif command == "report":
        report()
    else:
        print(__doc__)
        sys.exit(1)


if __name__ == "__main__":
    main()
